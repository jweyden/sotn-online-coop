"""The Saturn's long-coat Richter (RICHTER2.PRG/.CHR) -> PS1 Richter graphics.

His code is the same as Richter's (same animations, so the same 213 frames);
only the art and palette differ. Reads what sotn-decomp's Saturn asset tool
extracted (assets/saturn/player/RICHTER2) and the frame table in your
RICHTER2.PRG (0x060C0EA0), and writes, like mariasat-convert.py:
  OUT_SPR   sprites for high RAM (0x80600000)
  OUT_HDR   the overlay's sprite table, spritebank0 and palette

usage: richter2-convert.py DECOMP_DIR OUT_SPR OUT_HDR
"""
import importlib.util, json, os, struct, sys

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("conv", os.path.join(here, "mariasat-convert.py"))
conv = importlib.util.module_from_spec(spec)
spec.loader.exec_module(conv)

BASE = 0x060A5000
FRAMES_TABLE = 0x060C0EA0
FRAME_COUNT = 213

def main():
    decomp, out_spr, out_hdr = sys.argv[1:4]
    prg = open(decomp + "/disks/saturn/RICHTER2.PRG", "rb").read()
    man = json.load(open(decomp + "/assets/saturn/player/RICHTER2/manifest.json"))
    words = [int(w, 16) for w in man["palette"]["words"]]
    frames = []
    for k in range(FRAME_COUNT):
        a = struct.unpack_from(">I", prg, FRAMES_TABLE - BASE + 4 * k)[0] - BASE
        header = struct.unpack_from(">H", prg, a)[0]
        count = (header & 0x3F00) >> 8
        frames.append([struct.unpack_from(">HhhH", prg, a + 4 + 8 * i) for i in range(count)])

    images = {}
    def sprite(idx, flip):
        key = (idx, flip)
        if key not in images:
            sw, sh, px = conv.read_png8(decomp + "/assets/saturn/player/RICHTER2/sprites/%03d.png" % idx)
            w = ((sw * 4 + 4) // 5 + 3) & ~3
            data = bytes([w, sh, 0, 0])
            for y in range(sh):
                row = [px[y * sw + int((j + 0.5) * 5 / 4)] & 15 if int((j + 0.5) * 5 / 4) < sw else 0 for j in range(w)]
                if flip:
                    row.reverse()
                data += bytes(row[j] | (row[j + 1] << 4) for j in range(0, w, 2))
            images[key] = (len(images), data, sw, sh)
        return images[key]

    out = ["// Generated by tools/richter2-convert.py from your Saturn disc; do not edit."]
    bank = []
    for parts in frames:
        if not parts:
            bank.append(None)
            continue
        a, sx, sy, idx = parts[0]
        n, _, sw, sh = sprite(idx, bool(a & 0x10))
        bank.append((n, int(round((sx - sw / 2) / 1.25)), sy - sh // 2 - 1))
    blob, offsets = b"", []
    for key, (n, data, _, _) in sorted(images.items(), key=lambda kv: kv[1][0]):
        offsets.append(len(blob))
        blob += data + b"\0" * (-len(data) % 4)
    open(out_spr, "wb").write(blob)
    out.append("__attribute__((section(\".header.1\"))) u8* richter_sprites[%d] = {" % len(images))
    out += ["    (u8*)0x%08X," % (0x80600000 + o) for o in offsets]
    out += ["};"]
    for i, e in enumerate(bank):
        if i and e:
            out.append("static s16 spritebank0_%d[] = {0x%02X | 0x8000, %d, %d, 0};" % (i, e[0], e[1], e[2]))
    out.append("s16* spritebank0[] = {")
    out += ["    %s," % ("spritebank0_%d" % i if i and e else "0") for i, e in enumerate(bank)]
    out += ["};", "u16 g_Ric2Palette[16] = {" + ", ".join("0x%04X" % conv.ps1_color(c, i) for i, c in enumerate(words[:16])) + "};"]
    open(out_hdr, "w").write("\n".join(out) + "\n")
    print("richter2: %d sprites (%d bytes), %d frames" % (len(images), len(blob), len(bank)))

if __name__ == "__main__":
    main()
